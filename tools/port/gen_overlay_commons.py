#!/usr/bin/env python3
"""Give every overlay common symbol a real definition linked between the overlay data markers.

Overlays keep -fcommon, so a tentative definition repeated in several overlay
objects becomes one common symbol, which the linker places among the
executable's own. A real definition replaces common symbols of the same name.
This writes one, zero-initialized but placed in the data section, for each
common symbol of the overlay objects, so that src/port/overlay_data.c restores
them with the rest of the overlays' data.

usage: gen_overlay_commons.py --nm NM --output FILE OBJECT...
       (an argument starting with @ names a file listing objects, one per line)
"""
import argparse
import re
import subprocess
from pathlib import Path


def objects(args):
    for arg in args:
        if arg.startswith('@'):
            yield from (line.strip() for line in Path(arg[1:]).read_text().splitlines() if line.strip())
        else:
            yield arg


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--nm', required=True)
    parser.add_argument('--output', required=True, type=Path)
    parser.add_argument('objects', nargs='+')
    args = parser.parse_args()

    files = list(objects(args.objects))
    with open(files[0], 'rb') as f:
        darwin = f.read(4) in (b'\xcf\xfa\xed\xfe', b'\xfe\xed\xfa\xcf')
    sizes, defined = {}, set()
    for path in files:
        out = subprocess.run([args.nm, path], check=True, capture_output=True, text=True).stdout
        for line in out.splitlines():
            parts = line.split()
            if len(parts) == 3 and parts[1] in 'DBS':
                defined.add(parts[2][1:] if darwin and parts[2].startswith('_') else parts[2])
            if len(parts) == 3 and parts[1] == 'C':
                name = parts[2][1:] if darwin and parts[2].startswith('_') else parts[2]
                if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', name):
                    continue
                sizes[name] = max(sizes.get(name, 0), int(parts[0], 16))

    # A name that an overlay also defines already has its storage there.
    for name in defined:
        sizes.pop(name, None)
    section = '__DATA,__data' if darwin else '.data'
    lines = ['/* Generated by tools/port/gen_overlay_commons.py: real definitions of the overlays\' common',
             ' * symbols, in the data section between the overlay data markers. Do not edit. */', '']
    for name in sorted(sizes):
        lines.append(f'__attribute__((used, aligned(16), section("{section}"))) char {name}[{max(sizes[name], 1)}] = {{ 0 }};')
    text = '\n'.join(lines) + '\n'
    if not args.output.exists() or args.output.read_text() != text:
        args.output.write_text(text)
    print(f'{len(sizes)} overlay common symbols defined in {args.output.name}')


if __name__ == '__main__':
    main()
