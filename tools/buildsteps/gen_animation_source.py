#!/usr/bin/env python3
"""Generate the C definitions of a package's declared clips, or of a declared animation bank.

    gen_animation_source.py clips PACKAGE[:K] OUTPUT [--assets assets/USA]   every clip PACKAGE places, in its order,
                                                                           or its K-th run of back-to-back clips
    gen_animation_source.py bank NAME OUTPUT [--assets assets/USA]       the bank NAME, as its `symbol`

A clip is encoded from its USD at its placement's address (tools/peassets/animation/declared.py) and cut by the
encoder's layout: pose banks, records, track starts, then its `AnimationSet`, all static and named after the asset
(`characters/aya/idle` -> `_gAyaIdleClip`). A bank's slots point at those names, so its include follows its package's clips in
the same unit. Undeclared animation sets keep their per-array includes from gen_animation_inc.py.
"""
from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools" / "peassets"))

import asset_data  # noqa: E402
import asset_schema  # noqa: E402
from animation import codec, declared  # noqa: E402

HEADER = ("/* Generated by tools/buildsteps/gen_animation_source.py from {what}.\n   Do not edit: change the assets and rebuild. */\n"
          "\n#include \"gameplay/animation.h\"\n")


def ident(name: str) -> str:
    """A clip's C name, from its path less the group's first part: characters/aya/idle -> _gAyaIdleClip."""
    words = "_".join(name.split("/")[1:] if "/" in name else [name]).split("_")
    return "_g" + "".join(word[:1].upper() + word[1:] for word in words) + "Clip"


def package_record(package: str) -> dict:
    for key, rec in asset_data.ASSETS.items():
        if rec.get("type") in asset_schema.PACKAGE_TYPES and rec.get("package_name", key) == package:
            return rec
    raise SystemExit(f"{package}: no package of that name in the asset table")


def placed_clips(package: str) -> list[str]:
    return [p["name"] for p in package_record(package).get("embedded", ())
            if isinstance(p, dict) and asset_data.ASSETS[p["name"]]["type"] == "clip"]


def clip_runs(rec: dict, assets: dict) -> list[list[str]]:
    """A package's placed clips in runs: each run back to back in the package, the next run after other data (an
    actor's clips for its body, then its player clips elsewhere in its data). Each run is one include, at its place."""
    runs: list[list[str]] = []
    end = None
    for p in sorted((p for p in rec.get("embedded", ()) if isinstance(p, dict) and assets[p["name"]]["type"] == "clip"),
                    key=lambda p: p["offset"]):
        if end != p["offset"]:
            runs.append([])
        runs[-1].append(p["name"])
        end = p["offset"] + p["size"]
    return runs


def array(declaration: str, count: int, rows: list[str], bind: str | None = None) -> str:
    """One array. With `bind` (a registry key) the rows are the embedded build's initializer; the host build
    defines it zero-filled and registers it so the loader fills it from the user's disc."""
    if bind is None:
        return f"{declaration}[{count}] = {{\n" + "\n".join(rows) + "\n};\n"
    name = declaration.rsplit(" ", 1)[1]
    return (f"#ifdef PE_EMBED_ASSETS\n{declaration}[{count}] = {{\n" + "\n".join(rows) + f"\n}};\n#else\n{declaration}[{count}];\n#endif\n"
            f"#include \"port/asset_bind.h\"\nPE_ASSET_BIND(\"{bind}\", {name});\n")


def clip_layout(name: str, assets_root: Path) -> dict:
    """A clip's encoded blob cut into its arrays: [(kind, c array name, byte offset in the blob, byte size)] and the set."""
    assets, embedded = asset_data.ASSETS, asset_data.EMBEDDED_ASSETS
    blob = declared.encode(name, assets, embedded, assets_root)
    address = asset_schema.embedded_address(embedded[name])
    at = len(blob) - codec.SET_SIZE
    words = struct.unpack_from("<10I", blob, at)
    records_at, starts_at = words[0] - address, words[1] - address
    banks = {kind: words[2 + kind] - address for kind in range(8) if words[2 + kind]}
    ends = sorted(list(banks.values()) + [records_at])
    sym = assets[name].get("symbol") or ident(name)
    arrays = "_" + sym.lstrip("_")
    return {"blob": blob, "at": at, "records_at": records_at, "starts_at": starts_at, "banks": banks, "ends": ends,
            "sym": sym, "arrays": arrays}


def clip_arrays(name: str, assets_root: Path) -> list[tuple[str, str, int, int]]:
    """(C array name, element type, byte offset in the clip, byte size) of each data array of a clip."""
    L = clip_layout(name, assets_root)
    out = []
    for kind, offset in sorted(L["banks"].items(), key=lambda kv: kv[1]):
        end = L["ends"][L["ends"].index(offset) + 1]
        out.append((f"{L['arrays']}Bank{kind}", "AnimationPackedPose" if kind == codec.TRANSLATION else "AnimationPackedRotation",
                    offset, end - offset))
    out.append((f"{L['arrays']}Records", "AnimationRecord", L["records_at"], L["starts_at"] - L["records_at"]))
    out.append((f"{L['arrays']}TrackStarts", "u16", L["starts_at"], L["at"] - L["starts_at"]))
    return out


def clip_source(name: str, assets_root: Path, package: str | None = None) -> str:
    assets, embedded = asset_data.ASSETS, asset_data.EMBEDDED_ASSETS
    L = clip_layout(name, assets_root)
    blob, at, banks, ends = L["blob"], L["at"], L["banks"], L["ends"]
    records_at, starts_at, sym, arrays = L["records_at"], L["starts_at"], L["sym"], L["arrays"]
    storage = "static " if sym.startswith("_") else ""
    key = (lambda n: f"clip/{package}/{n}") if package else (lambda n: None)
    out = [f"/* {name} */"]
    for kind, offset in sorted(banks.items(), key=lambda kv: kv[1]):
        end = ends[ends.index(offset) + 1]
        if kind == codec.TRANSLATION:
            rows = [f"    {{ {', '.join(map(str, v))} }}," for v in struct.iter_unpack("<6h", blob[offset:end])]
            out.append(array("static AnimationPackedPose " + f"{arrays}Bank{kind}", len(rows), rows, key(f"{arrays}Bank{kind}")))
        else:
            rows = [f"    {{ {', '.join(str(a // codec.ANGLE_STEP) for a in codec._unpack_rotation(w))} }},"
                    for w, in struct.iter_unpack("<I", blob[offset:end])]
            out.append(array("static AnimationPackedRotation " + f"{arrays}Bank{kind}", len(rows), rows, key(f"{arrays}Bank{kind}")))
    records = [f"    {{ {p}, {d}, 0x{f:02X} }}," for p, d, f in struct.iter_unpack("<HBB", blob[records_at:starts_at])]
    out.append(array(f"static AnimationRecord {arrays}Records", len(records), records, key(f"{arrays}Records")))
    starts = struct.unpack_from(f"<{(at - starts_at) // 2}H", blob, starts_at)
    out.append(array(f"static u16 {arrays}TrackStarts", len(starts),
                     ["    " + ", ".join(map(str, starts[i:i + 8])) + "," for i in range(0, len(starts), 8)],
                     key(f"{arrays}TrackStarts")))
    pose_banks = ", ".join(f"[{kind}] = {arrays}Bank{kind}" for kind in sorted(banks))
    out.append(f"{storage}AnimationSet {sym} = {{\n    .records           = {arrays}Records,\n"
               f"    .trackStartIndices = {arrays}TrackStarts,\n    .poseBanks         = {{ {pose_banks} }},\n}};\n")
    return "\n".join(out)


def clips_source(package: str, assets_root: Path) -> str:
    """The clips a package places (`PACKAGE`), or one run of them (`PACKAGE:K`, the K-th from 1)."""
    package, _, run = package.partition(":")
    runs = clip_runs(package_record(package), asset_data.ASSETS)
    names = runs[int(run) - 1] if run else [n for r in runs for n in r]
    what = f"the clips {package} places" + (f", run {run} of {len(runs)}" if run else "")
    return HEADER.format(what=what) + "\n" + "\n".join(clip_source(n, assets_root, package) for n in names)


def clip_symbol(bank: str, clip: str) -> str:
    """A bank's clip by its C name: its own (`symbol`, else ident), or where another package the bank's package binds
    or requires places it, that package's export at its address."""
    assets = asset_data.ASSETS
    place, other = declared.bank_place(bank, clip, assets, asset_data.EMBEDDED_ASSETS)
    if other is None:
        return assets[clip].get("symbol") or ident(clip)
    import package
    address = declared.set_address(clip, asset_data.EMBEDDED_ASSETS, place)
    base = package.load_address(other, assets)
    symbol = next((e["symbol"] for e in (assets[other].get("exports") or {}).values() if base + e["at"] == address), None)
    if symbol is None:
        raise SystemExit(f"{bank}: binds {clip}, which {other} places at 0x{address:08X} but does not export")
    return symbol


# Tables a scene's AnimationBankCopyRequest points at. The request names up to ANIMATION_BANK_EXTENSION_CAPACITY clips
# even when the table behind it is shorter (the PS1 copied whatever followed); these are padded with NULL so a 64-bit
# host does not read past the array. Runtime-patched banks also reserve the
# slots listed below; all other tables keep the size of their placement.
COPY_REQUEST_SOURCES = frozenset({
    "_gAkropolisCafeteriaFollowUpPlayerAnimationSets",
    "_gAkropolisCafeteriaOpeningPlayerAnimationSets",
    "_gAkropolisForkedRoadAmbushPlayerAnimationSets",
    "_gAkropolisHelicopterLandingPadDeparturePlayerAnimationSets",
    "_gAkropolisPatioAmbushPlayerAnimationSets",
    "_gAkropolisPatioFollowUpPlayerAnimationSets",
    "_gAkropolisRoofGardenArrivalPlayerAnimationSets",
    "_gAkropolisRoofGardenEntrancePlayerAnimationSets",
    "_gAkropolisSanctuaryPlayerSceneAnimationSets",
    "_gAkropolisWestElevatorHallArrivalAnimationSets",
    "_gMistParkingCommand1PlayerAnimationSets",
    "_gMistParkingPlayerConversationAnimationSets",
    "_gMistParkingShopPlayerAnimationSets",
    "_gMistR18PlayerBriefingAnimationSets",
    "_gShootingGalleryPierceConversationPlayerAnimationSets",
    "_gShootingGalleryPierceGalleryPlayerAnimationSets",
})


# These native tables patch slot 5 during catch release. Their five-word disc
# placements are retained as metadata, but host storage must include that slot.
RUNTIME_BANK_MIN_SLOTS = {
    "_gDesertChaserFrontCatchPlayerAnimSets": 6,
    "_gDesertChaserRearCatchPlayerAnimSets": 6,
}


def bank_source(name: str) -> str:
    """A bank as a clip table, `AnimationSet* symbol[N]`: N its placement's words, each slot's clip, NULL past them."""
    assets = asset_data.ASSETS
    bank = assets[name]
    slots = declared.bank_slots(name, assets)
    entries = [f"    [{i}] = &{clip_symbol(name, clip)}," for i, clip in enumerate(slots) if clip]
    head = HEADER.format(what=f"the bank {name}, slots of {declared.bank_schema(name, assets)}")
    count = declared.bank_words(name, asset_data.EMBEDDED_ASSETS)
    if bank["symbol"] in COPY_REQUEST_SOURCES:
        count = max(count, 32)
    count = max(count, RUNTIME_BANK_MIN_SLOTS.get(bank["symbol"], 0))
    storage = "static " if bank["symbol"].startswith("_") else ""      # the project's TU-local names
    return f"{head}\n{storage}AnimationSet* {bank['symbol']}[{count}] = {{\n" + "\n".join(entries) + "\n};\n"


def schema_source(name: str) -> str:
    """A schema's slots as C constants, `<PREFIX>_ANIMATION_<SLOT> = index`, the prefix its local name less `_schema`
    (engine/animation/player_schema: PLAYER_ANIMATION_AIM_IDLE), or the group's own name for a group's `schema`
    (enemies/stranger/lesser/schema: LESSER_ANIMATION_IDLE): the indices code plays a bank's clips by."""
    slots = asset_data.ASSETS[name]["slots"]
    local = name.rsplit("/", 1)[-1]
    prefix = (name.rsplit("/", 2)[-2] if local == "schema" else local.removesuffix("_schema")).upper() + "_ANIMATION_"
    guard = "ASSETS_" + name.upper().replace("/", "_") + "_H"
    rows = [f"    {prefix}{slot.upper()} = {i}," for i, slot in enumerate(slots) if slot]
    head = HEADER.format(what=f"the animation schema {name}").split("\n\n#include")[0]
    return (f"{head}\n\n#ifndef {guard}\n#define {guard}\n\n/// The slots of {name}, by index.\nenum {{\n"
            + "\n".join(rows) + f"\n}};\n\n#endif // {guard}\n")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("kind", choices=("clips", "bank", "schema"))
    ap.add_argument("name", help="clips: the package; bank or schema: the asset's name")
    ap.add_argument("output", type=Path)
    ap.add_argument("--assets", type=Path, default=ROOT / "assets" / "USA")
    args = ap.parse_args()
    text = (clips_source(args.name, args.assets) if args.kind == "clips" else
            bank_source(args.name) if args.kind == "bank" else schema_source(args.name))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text)


if __name__ == "__main__":
    main()
