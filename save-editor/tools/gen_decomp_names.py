#!/usr/bin/env python3
"""Regenerates save-editor/src/names/decomp_names.rs from the decompilation headers.

* Nibble-bank flags: `include/main/event_flags.h` (checked flags) and the named
  entries of `include/main/gameflag_ids.h`; `GAME_FLAG_<HHH>` placeholders and
  value enums are left out (the editor shows those positions raw).
* Area names: the `GAME_AREA_*` enum of `include/main/areas.h`, grouped by stage.
* Stage-bank object slots: the `MAP_<STAGE>_OBJECT_SLOT_*` enums of the map
  menus (`src/mapui/map_shelter/map_shelter.c`, `src/mapui/map_neo_ark/map_neo_ark.c`).

Run from the repository root:

    python3 -I save-editor/tools/gen_decomp_names.py . save-editor/src/names/decomp_names.rs
"""
import re
import sys

VALUE_SUFFIXES = re.compile(r"_(UNMARKED|PASSED|LOCKED|UNHEARD|LOOP_ACTIVE|LOOP_DONE)$")
PLACEHOLDER = re.compile(r"_[0-9A-F]{3}$")


def parse(path, prefix):
    out, doc = [], []
    for ln, line in enumerate(open(path), 1):
        s = line.strip()
        if s.startswith("///"):
            doc.append(s[3:].strip())
            continue
        m = re.match(r"(" + prefix + r"[A-Z0-9_]+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*,?\s*(//\s*(.*))?$", s)
        if m:
            out.append((int(m.group(2), 0), m.group(1), " ".join(doc) or (m.group(4) or ""), ln))
        doc = []
    return out


ACRONYMS = {"MP", "MD", "SP", "NMC", "MIST", "GPS", "SUV", "EVE", "AS", "PA", "G", "R"}


def humanize(constant):
    """`B1_ARMORY_9MM_HYDRA` -> `B1 Armory 9mm Hydra`."""
    words = []
    for w in constant.split("_"):
        if w == "9MM":
            words.append("9mm")
        elif any(c.isdigit() for c in w) or w in ACRONYMS:
            words.append(w)
        else:
            words.append(w.capitalize())
    return " ".join(words)


def summary(d):
    d = d.replace("`", "")
    parts = re.split(r"(?<!No)(?<!Mr)(?<=[.;])\s+", d)
    s = ""
    for part in parts:
        s = (s + " " + part).strip()
        if len(s) >= 70:
            break
    if len(s) > 240:
        s = s[:237].rstrip() + "..."
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main(root, out):
    ev = parse(f"{root}/include/main/event_flags.h", "EVENT_FLAG_")
    ev = [e for e in ev if not VALUE_SUFFIXES.search(e[1])
          and not e[1].startswith(("EVENT_FLAG_STORY_CHAPTER_", "EVENT_FLAG_OBJECTIVE_"))
          and "RESERVED_PLAY_TIME" not in e[1]]
    gi = [g for g in parse(f"{root}/include/main/gameflag_ids.h", "GAME_FLAG_") if not PLACEHOLDER.search(g[1])]
    with open(out, "w") as f:
        f.write("//! Area, flag and object-slot names, generated by `save-editor/tools/gen_decomp_names.py` from the\n")
        f.write("//! decompilation. Each entry records the definition it came from. Regenerate rather than\n")
        f.write("//! hand-edit.\n\n")
        f.write("use super::{NamedFlag, ObjectSlot};\n\n")
        f.write("/// Named nibble-bank flags (`GameFlagNibbleBank`), sorted by nibble index.\n")
        f.write("pub const NIBBLE_FLAGS: &[NamedFlag] = &[\n")
        seen = set()
        for v, n, d, ln in sorted(ev + gi):
            if v in seen:
                continue
            seen.add(v)
            src = ("include/main/event_flags.h" if n.startswith("EVENT") else "include/main/gameflag_ids.h") + f":{ln}"
            f.write(f'    NamedFlag {{ index: {v:#05x}, name: "{n}", source: "{src}", doc: "{summary(d)}" }},\n')
        f.write("];\n\n")
        f.write("/// `(stage, area, name, source)` for every `GAME_AREA_*` constant.\n")
        f.write("pub const AREA_NAMES: &[(u8, u8, &str, &str)] = &[\n")
        stage = 0
        stages = {"AKROPOLIS": 1, "DRYFIELD": 2, "DRYFIELD_NIGHT": 3, "MINE_SHELTER": 4, "SHELTER_NEO_ARK": 5}
        for ln, line in enumerate(open(f"{root}/include/main/areas.h"), 1):
            m = re.match(r"\s*// GAME_STAGE_(\w+)", line)
            if m:
                stage = stages[m.group(1)]
                continue
            m = re.match(r"\s*GAME_AREA_(\w+)\s*=\s*(\d+)", line)
            if m and stage:
                label = humanize(m.group(1))
                f.write(f'    ({stage}, {m.group(2)}, "{label}", "include/main/areas.h:{ln}"),\n')
        f.write("];\n\n")
        f.write("/// Named two-bit object-state slots of the stage banks (`GameFlagStageHeader::objectStates`).\n")
        f.write("pub const OBJECT_SLOTS: &[ObjectSlot] = &[\n")
        for stage, path, prefix in [
            (4, "src/mapui/map_shelter/map_shelter.c", "MAP_SHELTER_OBJECT_SLOT_"),
            (5, "src/mapui/map_neo_ark/map_neo_ark.c", "MAP_NEO_ARK_OBJECT_SLOT_"),
        ]:
            for v, n, _d, ln in sorted(parse(f"{root}/{path}", prefix)):
                label = humanize(n[len(prefix):])
                f.write(f'    ObjectSlot {{ stage: {stage}, slot: {v}, name: "{label}", source: "{path}:{ln}" }},\n')
        f.write("];\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
