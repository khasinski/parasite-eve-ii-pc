#!/usr/bin/env python3
"""Regenerates save-editor/src/names/item_names.rs: item id -> short name + category.

Reads the item catalog decoded from the user's own disc by `tools/peassets`
(`assets/<region>/inventory/catalog.toml` and the per-item `item.toml` files it
lists; `assets/` is not committed). Only each item's short `name` field and the
classification bits the decompilation documents are used; descriptions are not
copied. Run from the repository root:

    python3 -I save-editor/tools/gen_item_names.py assets/USA save-editor/src/names/item_names.rs
"""
import re
import sys

# Ids whose catalog names repeat; the suffix tells them apart in the editor.
DISAMBIGUATE = {
    0xB9: "Battery (Hypervelocity)",
    0xBB: "Battery (M4A1 Hammer)",
    0xBE: "Battery (M4A1 Javelin)",
    0x12C: "Jumper Plug (2nd)",
    0x12D: "Micro Device (2nd)",
}
# Weapon add-ons: clip holders, the P08 snail magazine and the M4A1 mounts.
WEAPON_PARTS = {0x09, 0x0A, 0x0C, 0x42, 0x43, 0x44, 0x45, 0x46}


def main(root, out):
    catalog = open(f"{root}/inventory/catalog.toml").read()
    rows = []
    section = None
    for line in catalog.splitlines():
        m = re.match(r"\[(\w+)\]", line)
        if m:
            section = m.group(1)
            continue
        m = re.match(r'(0x[0-9A-Fa-f]+) = "(.+)"', line)
        if not m or section is None:
            continue
        item_id, path = int(m.group(1), 16), m.group(2)
        text = open(f"{root}/{path}.toml").read()
        name = re.search(r'^name = "(.*)"', text, re.M)
        name = name.group(1) if name else ""
        if not name or "blank_row = true" in text:
            continue
        medicine = re.search(r"^medicine = true", text, re.M) is not None
        no_attachment = re.search(r"^no_attachment = true", text, re.M) is not None
        caliber = re.search(r'^caliber = "(.*)"', text, re.M)
        if section == "items":
            if medicine:
                cat = "Consumable"
            elif item_id in WEAPON_PARTS:
                cat = "WeaponPart"
            elif no_attachment:
                cat = "Tool"
            else:
                cat = "Attachment"
        elif section == "parasite_energy":
            cat = "ParasiteEnergy"
            name = f"{name} Lv{(item_id - 0x0F) % 3 + 1}"
        elif section == "armor":
            cat = "Armor"
        elif section == "weapons":
            cat = "Weapon"
        elif section == "ammunition":
            cat = "BuiltInSupply" if caliber and caliber.group(1) in ("battery", "fuel") else "Ammunition"
        elif section == "key_items":
            cat = "KeyItem"
        else:
            continue
        name = DISAMBIGUATE.get(item_id, name)
        rows.append((item_id, name, cat))
    rows.sort()
    with open(out, "w") as f:
        f.write("//! Item id -> short in-game name and category.\n//!\n")
        f.write("//! Generated by `save-editor/tools/gen_item_names.py` from the disc's item catalog\n")
        f.write("//! (`gItemDescriptors` / `gItemKeyDescriptors`, src/gameplay/item_catalog.c). Only the\n")
        f.write("//! short name field is kept. Regenerate rather than hand-edit.\n\n")
        f.write("use super::ItemCategory::{self, *};\n\n")
        f.write("/// `(item id, name, category)`, sorted by id.\n")
        f.write("pub const ITEM_NAMES: &[(u16, &str, ItemCategory)] = &[\n")
        for item_id, name, cat in rows:
            esc = name.replace("\\", "\\\\").replace('"', '\\"')
            f.write(f'    ({item_id:#05x}, "{esc}", {cat}),\n')
        f.write("];\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
